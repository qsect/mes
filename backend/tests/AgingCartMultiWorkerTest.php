<?php
declare(strict_types=1);

/**
 * 老化车「多人同时维修」时长口径单元测试
 *
 * ★ 背景：工单落成两个口径的时长，含义不同，这里把它们的关系固化下来：
 *   - 修复跨度 span：第一个人开工 → 收工（WorkDuration 扣非工时后）
 *   - 投入工时 work：各参与人自身有效时长之和
 *
 * 关键结论：**多人重叠时 投入工时 > 修复跨度 是正常且正确的**，
 *   不能因为「比工单跨度大」就当成重复计算去去重；
 *   反过来，接力式维修（无重叠）时两者应当相等。
 * 这两条最容易在后续改动中被"顺手修正"，故写成断言守住。
 *
 * 固定日期说明：2026-10-12 是星期一，故 10-14 是周三（工作日 8:30-18:00，午休不计）。
 */

require_once __DIR__ . '/../app/Core/WorkDuration.php';

use App\Core\WorkDuration;

/**
 * 模拟一张工单的结算：给定各人「加入→离开」区间，算出两个口径
 *
 * @param array $segments [['from'=>'Y-m-d H:i:s','to'=>'Y-m-d H:i:s'], ...]
 * @return array ['span'=>int, 'work'=>int]
 */
function settle(array $segments): array
{
    // 跨度：取最早的加入时刻到最晚的离开时刻
    $froms = array_column($segments, 'from');
    $tos = array_column($segments, 'to');
    sort($froms);
    rsort($tos);

    $span = WorkDuration::minutes(reset($froms), reset($tos));

    // 投入工时：各人各自独立计时后求和
    $work = 0;
    foreach ($segments as $seg) {
        $work += WorkDuration::minutes($seg['from'], $seg['to']);
    }

    return ['span' => $span, 'work' => $work];
}

// ---------- 单人：两个口径必然相等 ----------

test('单人维修：投入工时等于修复跨度', function () {
    $r = settle([['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00']]);
    assert_eq(60, $r['span']);
    assert_eq(60, $r['work']);
    assert_eq($r['span'], $r['work']);
});

// ---------- 两人完全重叠：投入工时应为跨度的 2 倍 ----------

test('两人同时全程参与：投入工时 = 跨度 × 2', function () {
    $r = settle([
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
    ]);
    assert_eq(60, $r['span']);
    assert_eq(120, $r['work'], '两人同修 1 小时，人力投入应为 2 小时，不可去重');
});

test('三人同时全程参与：投入工时 = 跨度 × 3', function () {
    $r = settle([
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
    ]);
    assert_eq(60, $r['span']);
    assert_eq(180, $r['work']);
});

// ---------- 接力维修（无重叠）：两者相等 ----------

test('接力维修无重叠：投入工时等于修复跨度', function () {
    $r = settle([
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:00:00'],
        ['from' => '2026-10-14 10:00:00', 'to' => '2026-10-14 11:00:00'],
    ]);
    assert_eq(120, $r['span']);
    assert_eq(120, $r['work']);
});

// ---------- 部分重叠 ----------

test('部分重叠：第二人中途加入，按各自实际时间累计', function () {
    $r = settle([
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 11:00:00'], // 甲：2h
        ['from' => '2026-10-14 10:00:00', 'to' => '2026-10-14 11:00:00'], // 乙：1h
    ]);
    assert_eq(120, $r['span'], '跨度由甲决定，为 2 小时');
    assert_eq(180, $r['work'], '投入工时为 2h + 1h = 3 小时');
});

test('有人先离开：先走的人计时停在他离开的时刻', function () {
    $r = settle([
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 09:30:00'], // 甲先走：30min
        ['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 10:30:00'], // 乙继续：90min
    ]);
    assert_eq(90, $r['span'], '跨度到收工为止');
    assert_eq(120, $r['work'], '30 + 90 = 120 分钟');
});

// ---------- 非计时段同样对「每个人」分别生效 ----------

test('多人维修时，非计时段对每个人分别扣除（非一次性扣除）', function () {
    // 两人都在 11:30-13:30，中间跨午休 12:00-13:00：
    // 每人有效时长 = 11:30-12:00(30) + 13:00-13:30(30) = 60 分钟
    $r = settle([
        ['from' => '2026-10-14 11:30:00', 'to' => '2026-10-14 13:30:00'],
        ['from' => '2026-10-14 11:30:00', 'to' => '2026-10-14 13:30:00'],
    ]);
    assert_eq(60, $r['span'], '跨度扣除午休后为 1 小时');
    assert_eq(120, $r['work'], '两人各自扣除午休后合计 2 小时');
});

test('单人跨午休作为对照，验证上述假定的基数', function () {
    assert_eq(60, WorkDuration::minutes('2026-10-14 11:30:00', '2026-10-14 13:30:00'));
});

// ---------- 边界 ----------

test('只有落库时刻缺失的异常数据不会导致负数', function () {
    assert_eq(0, WorkDuration::minutes('2026-10-14 11:00:00', '2026-10-14 10:00:00'));
});

test('无人参与的工单：投入工时为 0', function () {
    // settle 不允许空数组（跨度无从计算），这里断言提示上层必须保证至少一人
    $r = settle([['from' => '2026-10-14 09:00:00', 'to' => '2026-10-14 09:00:00']]);
    assert_eq(0, $r['work']);
    assert_eq(0, $r['span']);
});
